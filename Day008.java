public class day008{
  public static void main(String[] args){
  // 1. Deklarasi //
    int a;
    String b;
    /* 
     * Deklarasi adalah proses membuat 
     * atau memperkenalkan sebuah variabel 
     * dengan menentukan tipe data dan nama 
     * variabel, tetapi belum memberikan nilai.
     */
    
  // 2. Inisialisasi //
    a = 6;
    b = "nilai";
    /*
     *  Inisialisasi adalah proses memberikan
     *  nilai awal kepada variabel. 
     */

   // 3. update variabel //
    boolean c = true; // nilai awal //
    c = false; // update//
    /*
     * mengubah nilai awal variabel 
     */
    System.out.println(a);
    System.out.println(b);
    System.out.println(c);
  }
}
